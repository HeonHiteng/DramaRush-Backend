export type Lang = 'en' | 'zh';
export const MESSAGES: Record<Lang, Record<MsgKey, string>> = { en, zh };

const STORAGE_KEY = 'keybox-admin:lang';
let current: Lang = readStoredLang();

function readStoredLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'zh' ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** Current-language text. Components should call useI18n() so they re-render on a switch. */
export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  return format(MESSAGES[current][key], vars);
}

/** For toLocaleString — dates follow the UI language. */
export function currentLocale(): string {
  return current === 'zh' ? 'zh-CN' : 'en-US';
}

interface I18nState {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: typeof t;
}

const I18nContext = createContext<I18nState>({ lang: current, setLang: () => {}, t });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);
  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }, [lang]);
  const setLang = useCallback((next: Lang) => {
    current = next;
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* private mode: the choice just isn't remembered */
    }
    setLangState(next);
  }, []);
  // A fresh `t` per language so memoized consumers notice the change.
  const value = { lang, setLang, t: (key: MsgKey, vars?: Record<string, string | number>) => format(MESSAGES[lang][key], vars) };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  return useContext(I18nContext);
}

export function LangSwitch({ className = '' }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <div className={`lang-switch ${className}`} role="group" aria-label="Language">
      <button type="button" className={lang === 'en' ? 'on' : ''} aria-pressed={lang === 'en'} onClick={() => setLang('en')}>
        EN
      </button>
      <button type="button" className={lang === 'zh' ? 'on' : ''} aria-pressed={lang === 'zh'} onClick={() => setLang('zh')} lang="zh-CN">
        中文
      </button>
    </div>
  );
}
